import { readFile, readdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { optimize } from "svgo";

/** Keep accessibility and externally referenced IDs, classes, and element types stable. */
export function optimizePublicSvg(source) {
  return optimize(source, {
    plugins: [
      {
        name: "preset-default",
        params: {
          overrides: {
            cleanupIds: false,
            removeUselessDefs: false,
            removeDesc: false,
            removeHiddenElems: false,
            inlineStyles: false,
            convertShapeToPath: false,
            convertEllipseToCircle: false,
            collapseGroups: false,
          },
        },
      },
    ],
  }).data;
}

export async function optimizePublicSvgFiles(directory) {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const file = resolve(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await optimizePublicSvgFiles(file)));
    else if (entry.name.endsWith(".svg")) {
      const source = await readFile(file, "utf8");
      await writeFile(file, optimizePublicSvg(source));
      files.push(file);
    }
  }
  return files;
}

export function publicInlineSvgOptimizer() {
  const cache = new Map();
  return (document) => {
    for (const image of document.querySelectorAll("svg")) {
      // HTML serialization leaves foreignObject's void elements unclosed.
      // SVGO parses XML, including the XHTML labels generated by Mermaid.
      const source = new document.defaultView.XMLSerializer().serializeToString(image);
      if (!cache.has(source)) cache.set(source, optimizePublicSvg(source));
      image.outerHTML = cache.get(source);
    }
  };
}
