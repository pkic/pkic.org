import { createReadStream } from "node:fs";
import { lstat, readdir } from "node:fs/promises";
import { resolve } from "node:path";
import { createHash } from "node:crypto";
import {
  publicationIntegrityHashInput,
  sitePublicationIntegrityPathSchema,
  sitePublicationIntegritySchema,
} from "../../assets/shared/schemas/site-publication-release.ts";

export const synchronizedPublicationDirectories = ["_assets", "_published", "pagefind", "js/built"];

async function sourceEntry(root, path) {
  sitePublicationIntegrityPathSchema.parse(path);
  const segments = path.split("/");
  let info;
  for (let index = 0; index < segments.length; index++) {
    info = await lstat(resolve(root, ...segments.slice(0, index + 1)));
    if (info.isSymbolicLink()) throw new Error(`Publication symlinks are unsupported: ${path}`);
    if (index < segments.length - 1 && !info.isDirectory()) throw new Error(`Unsafe publication ancestor: ${path}`);
  }
  return info;
}

async function digestFile(root, path) {
  sitePublicationIntegrityPathSchema.parse(path);
  const location = resolve(root, path);
  const info = await sourceEntry(root, path);
  if (!info.isFile() || info.isSymbolicLink()) throw new Error(`Publication integrity requires a regular file: ${path}`);
  const hash = createHash("sha256");
  let bytes = 0;
  for await (const chunk of createReadStream(location)) {
    bytes += chunk.length;
    hash.update(chunk);
  }
  if (bytes !== info.size) throw new Error(`Publication changed while hashing: ${path}`);
  return { sha256: hash.digest("hex"), bytes };
}

async function directoryFiles(root, path, files) {
  let entries;
  try {
    const info = await sourceEntry(root, path);
    if (info.isSymbolicLink() || !info.isDirectory()) throw new Error(`Unsafe publication directory: ${path}`);
    entries = await readdir(resolve(root, path), { withFileTypes: true });
  } catch (error) {
    if (error.code === "ENOENT") return;
    throw error;
  }
  for (const entry of entries) {
    const child = `${path}/${entry.name}`;
    sitePublicationIntegrityPathSchema.parse(child);
    if (entry.isSymbolicLink()) throw new Error(`Publication symlinks are unsupported: ${child}`);
    if (entry.isDirectory()) await directoryFiles(root, child, files);
    else if (entry.isFile()) files.add(child);
    else throw new Error(`Publication contains a non-file entry: ${child}`);
    if (files.size > 100_000) throw new Error("Publication integrity inventory exceeds its bound");
  }
}

/** Hash owned output and every synchronized lazy-import/search/media asset. */
export async function createReleaseIntegrity(root, ownedFiles) {
  const paths = new Set(ownedFiles);
  for (const directory of synchronizedPublicationDirectories) await directoryFiles(root, directory, paths);
  if (paths.size > 100_000) throw new Error("Publication integrity inventory exceeds its bound");
  const files = {};
  // Sequential stream hashing bounds memory independently of archive/font size.
  for (const path of [...paths].sort()) files[path] = await digestFile(root, path);
  return sitePublicationIntegritySchema.parse({
    algorithm: "sha256",
    digest: createHash("sha256").update(publicationIntegrityHashInput(files)).digest("hex"),
    files,
  });
}

/** Validate before installation; missing, changed or injected assets fail closed. */
export async function verifyReleaseIntegrity(root, release) {
  if (!release.integrity) throw new Error("Publication integrity is missing");
  const actual = await createReleaseIntegrity(root, [
    ...release.files,
    ...Object.keys(release.integrity.files).filter((path) => path === "_headers" || path === "_redirects"),
  ]);
  if (publicationIntegrityHashInput(actual.files) !== publicationIntegrityHashInput(release.integrity.files) ||
      actual.digest !== release.integrity.digest)
    throw new Error("Publication integrity does not match its generated bytes");
}
