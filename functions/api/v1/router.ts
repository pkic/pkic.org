import users_Router from "./users/router";
import portal_Router from "./portal/router";
import votes_Router from "./votes/router";
import webhooks_Router from "./webhooks/router";

const app = new Hono();
export const openapi = fromHono(app);

app.onError((error, c) => {
  const request = c.req.raw;
  const requestId =
    ((c as any).get("requestId") as string | undefined) ?? request.headers.get("x-request-id") ?? crypto.randomUUID();
  const sensitive = (c as any).get("sensitive") === true;
  return finalizeApiResponse(request, handleError(error), sensitive, requestId);
});
app.use("*", middleware_l);
openapi.get("/geo", GeoGet);
app.on("HEAD", "/geo", GeoGet_l);
openapi.get("/", RouteGet);
openapi.route("/admin", admin_Router);
openapi.route("/auth", auth_Router);
openapi.route("/donations", donations_Router);
openapi.route("/email", email_Router);
openapi.route("/events", events_Router);
openapi.route("/headshots", headshots_Router);
openapi.route("/groups", groups_Router);
openapi.route("/internal", internal_Router);
openapi.route("/invites", invites_Router);
openapi.route("/leadership", leadership_Router);
openapi.route("/meeting-guests", meetingGuests_Router);
openapi.route("/me", me_Router);
openapi.route("/members", members_Router);
openapi.route("/og", og_Router);
openapi.route("/organizations", organizations_Router);
openapi.route("/operations", operations_Router);
openapi.route("/proposals", proposals_Router);
openapi.route("/registrations", registrations_Router);
openapi.route("/sponsors", sponsors_Router);
openapi.route("/sponsorship", sponsorship_Router);
openapi.route("/sponsorships", sponsorships_Router);
openapi.route("/sponsor-portal", sponsorPortal_Router);
openapi.route("/system", system_Router);
openapi.route("/users", users_Router);
openapi.route("/portal", portal_Router);
openapi.route("/votes", votes_Router);
openapi.route("/webhooks", webhooks_Router);

export default openapi;
